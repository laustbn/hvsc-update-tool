void logError(ofstream& errorFile, std::string lineContent,
              std::string errorMessage, int iLineNum, Mode mode,
              int& errorCount);

ErrorLogger mkErrorLogger(ofstream& errorFile, Mode mode, int& errorCount) {
  return [mode, &errorCount, &errorFile](
             std::string lineContent, std::string errorMessage, int lineNum) {
    logError(errorFile, lineContent, errorMessage, lineNum, mode, errorCount);
  };
}

// Returns false if user prompting is disabled by setting the HVSC_NO_PROMPT
// environment variable. This is to facilitate automated testing.
bool prompt_user() {
  auto str = std::getenv("HVSC_NO_PROMPT");
  return str == nullptr;
}

// Until we add fmt/std::format, this will do
std::string numToStr(int value, int width) {
  std::ostringstream oss;
  oss << std::setw(width) << std::setfill('0') << value;
  return oss.str();
}

// --------------------------------------------------------------------------
// OS-dependent application exit() wrapper.

inline void appExit(int returnValue) {
#if defined(_MSC_VER)
  HANDLE hStdin = GetStdHandle(STD_INPUT_HANDLE);
  DWORD fdwMode, fdwOldMode;
  bool newMode = true;
  if (!GetConsoleMode(hStdin, &fdwOldMode)) newMode = false;
  fdwMode = fdwOldMode & ~(ENABLE_LINE_INPUT | ENABLE_ECHO_INPUT);
  fdwMode |= ENABLE_PROCESSED_INPUT;
  if (!SetConsoleMode(hStdin, fdwMode)) newMode = false;
  // If we could not change console mode, better leave immediately.
  if (newMode) {
    cout << endl << "--- PRESS <RETURN> TO EXIT ---" << endl << flush;
    FlushConsoleInputBuffer(hStdin);
    DWORD count;
    char readBuf[2];
    if (prompt_user()) ReadConsole(hStdin, &readBuf, 1, &count, 0);
    SetConsoleMode(hStdin, fdwOldMode);
  }
#endif
  exit(returnValue);
}

